#!/usr/bin/env python3
"""Embed the two OFL-licensed UI font assets into the single native ELF.
The generated header stays in build/, never in the repository or PS5 storage.
"""
from pathlib import Path
import hashlib
import sys

root = Path(__file__).resolve().parents[1]
output = root / "build" / "embedded_assets.h"
output.parent.mkdir(parents=True, exist_ok=True)
resources = (
    ("niak_manrope_font", root / "assets" / "manrope.ttf"),
    ("niak_serif_font", root / "assets" / "instrument-serif.ttf"),
)
with output.open("w", encoding="ascii") as stream:
    stream.write("/* Generated by native/tools/embed_assets.py. Never edit. */\n")
    stream.write("#ifndef NIAK_EMBEDDED_ASSETS_H\n#define NIAK_EMBEDDED_ASSETS_H\n")
    for symbol, path in resources:
        data = path.read_bytes()
        if not data or len(data) > 2_000_000:
            raise SystemExit(f"Refusing unexpected font size: {path}")
        digest = hashlib.sha256(data).hexdigest()
        stream.write(f"/* {path.name}: {len(data)} bytes, SHA256={digest} */\n")
        stream.write(f"static const unsigned char {symbol}[] = {{\n")
        for offset in range(0, len(data), 24):
            chunk = data[offset:offset + 24]
            stream.write(" " + ",".join(f"0x{value:02x}" for value in chunk) + ",\n")
        stream.write("};\n")
    stream.write("#endif\n")
print(f"Embedded {sum(x[1].stat().st_size for x in resources)} bytes in {output}")
